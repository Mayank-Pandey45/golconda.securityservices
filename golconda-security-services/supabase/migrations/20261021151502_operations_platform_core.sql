-- Salary adjustments require an explicit approval transition. Authenticated
-- admins may create/read them but cannot edit or delete financial history.
drop policy if exists "Admins manage operations rows" on public.salary_adjustments;
drop policy if exists "Admins read salary adjustments" on public.salary_adjustments;
drop policy if exists "Admins record salary adjustments" on public.salary_adjustments;
create policy "Admins read salary adjustments" on public.salary_adjustments for select to authenticated
  using (exists (select 1 from public.admin_users where user_id = (select auth.uid())));
create policy "Admins record salary adjustments" on public.salary_adjustments for insert to authenticated
  with check (exists (select 1 from public.admin_users where user_id = (select auth.uid())));
revoke update, delete on table public.salary_adjustments from authenticated;

create or replace function public.approve_salary_adjustment(p_adjustment_id bigint, p_actor_id uuid)
returns boolean
language plpgsql
security invoker
set search_path = pg_catalog
as $$
begin
  if p_actor_id is null or not exists (select 1 from public.admin_users where user_id = p_actor_id) then raise exception 'Administrator access is required'; end if;
  perform set_config('request.jwt.claim.sub', p_actor_id::text, true);
  update public.salary_adjustments set is_approved = true, approved_by = p_actor_id, approved_at = now()
    where id = p_adjustment_id and not is_approved;
  return found;
end;
$$;
