-- Site editing and assignment changes are atomic and require a server-verified
-- administrator. The API validates request data before calling this function;
-- foreign keys and RLS remain a second line of defense.
create or replace function public.save_site_with_assignments(
  p_site jsonb,
  p_site_id bigint,
  p_guard_ids bigint[],
  p_supervisor_ids bigint[],
  p_field_officer_ids bigint[],
  p_actor_id uuid
)
returns bigint
language plpgsql
security invoker
set search_path = pg_catalog
as $$
declare
  saved_site_id bigint;
  site_title text := nullif(btrim(p_site ->> 'title'), '');
  site_code_value text := nullif(upper(btrim(p_site ->> 'site_code')), '');
begin
  if p_actor_id is null or not exists (select 1 from public.admin_users where user_id = p_actor_id) then
    raise exception 'Administrator access is required';
  end if;
  perform set_config('request.jwt.claim.sub', p_actor_id::text, true);
  if site_title is null or length(site_title) > 160 then raise exception 'A site name of 1 to 160 characters is required'; end if;
  if site_code_value is null or length(site_code_value) > 64 or site_code_value !~ '^[A-Z0-9_-]+$' then
    raise exception 'A stable site code containing letters, numbers, hyphens, or underscores is required';
  end if;
  if coalesce(p_site ->> 'status', 'active') not in ('active', 'inactive') then raise exception 'Invalid site status'; end if;
  if coalesce(p_site ->> 'service_taken', 'SECURITY GUARD') not in ('SECURITY GUARD', 'ASO', 'BOTH') then raise exception 'Invalid service type'; end if;
  if p_site_id is not null then
    update public.sites set
      site_code = site_code_value,
      title = site_title,
      phone_numbers = coalesce(p_site ->> 'phone_numbers', ''),
      total_salary = coalesce(p_site ->> 'total_salary', ''),
      service_taken = coalesce(p_site ->> 'service_taken', 'SECURITY GUARD'),
      given_emails = coalesce(p_site ->> 'given_emails', ''),
      status = coalesce(p_site ->> 'status', 'active'),
      security_guard_monthly_billing = nullif(p_site ->> 'security_guard_monthly_billing', '')::numeric,
      aso_monthly_billing = nullif(p_site ->> 'aso_monthly_billing', '')::numeric,
      payroll_effective_date = nullif(p_site ->> 'payroll_effective_date', '')::date,
      esi_applicable = nullif(p_site ->> 'esi_applicable', '')::boolean,
      esi_contribution_rate = nullif(p_site ->> 'esi_contribution_rate', '')::numeric,
      pf_applicable = nullif(p_site ->> 'pf_applicable', '')::boolean,
      pf_contribution_rate = nullif(p_site ->> 'pf_contribution_rate', '')::numeric,
      payroll_notes = coalesce(p_site ->> 'payroll_notes', ''),
      updated_at = now()
    where id = p_site_id returning id into saved_site_id;
    if saved_site_id is null then raise exception 'Site was not found'; end if;
  else
    insert into public.sites (
      site_code, title, phone_numbers, total_salary, service_taken, given_emails, status,
      security_guard_monthly_billing, aso_monthly_billing, payroll_effective_date,
      esi_applicable, esi_contribution_rate, pf_applicable, pf_contribution_rate, payroll_notes
    ) values (
      site_code_value, site_title, coalesce(p_site ->> 'phone_numbers', ''),
      coalesce(p_site ->> 'total_salary', ''), coalesce(p_site ->> 'service_taken', 'SECURITY GUARD'),
      coalesce(p_site ->> 'given_emails', ''), coalesce(p_site ->> 'status', 'active'),
      nullif(p_site ->> 'security_guard_monthly_billing', '')::numeric,
      nullif(p_site ->> 'aso_monthly_billing', '')::numeric,
      nullif(p_site ->> 'payroll_effective_date', '')::date,
      nullif(p_site ->> 'esi_applicable', '')::boolean,
      nullif(p_site ->> 'esi_contribution_rate', '')::numeric,
      nullif(p_site ->> 'pf_applicable', '')::boolean,
      nullif(p_site ->> 'pf_contribution_rate', '')::numeric,
      coalesce(p_site ->> 'payroll_notes', '')
    ) returning id into saved_site_id;
  end if;

  update public.guard_site_assignments set valid_to = current_date
  where site_id = saved_site_id and valid_to is null
    and not (guard_id = any(coalesce(p_guard_ids, array[]::bigint[])));
  update public.supervisor_site_assignments set valid_to = current_date
  where site_id = saved_site_id and valid_to is null
    and not (supervisor_id = any(coalesce(p_supervisor_ids, array[]::bigint[])));
  update public.field_officer_site_assignments set valid_to = current_date
  where site_id = saved_site_id and valid_to is null
    and not (field_officer_id = any(coalesce(p_field_officer_ids, array[]::bigint[])));

  insert into public.guard_site_assignments(guard_id, site_id, valid_from, created_by)
  select requested_id, saved_site_id, current_date, p_actor_id
  from (select distinct unnest(coalesce(p_guard_ids, array[]::bigint[])) as requested_id) requested
  where exists (select 1 from public.guards where id = requested.requested_id)
    and not exists (select 1 from public.guard_site_assignments a where a.guard_id = requested.requested_id and a.site_id = saved_site_id and a.valid_to is null);
  if cardinality(coalesce(p_guard_ids, array[]::bigint[])) <> (select count(distinct item.id) from unnest(coalesce(p_guard_ids, array[]::bigint[])) as item(id)) then raise exception 'Guard assignment contains duplicate IDs'; end if;
  if exists (select 1 from unnest(coalesce(p_guard_ids, array[]::bigint[])) as item(id) where not exists (select 1 from public.guards where guards.id = item.id)) then raise exception 'A selected guard was not found'; end if;

  insert into public.supervisor_site_assignments(supervisor_id, site_id, valid_from, created_by)
  select requested_id, saved_site_id, current_date, p_actor_id
  from (select distinct unnest(coalesce(p_supervisor_ids, array[]::bigint[])) as requested_id) requested
  where exists (select 1 from public.supervisors where id = requested.requested_id)
    and not exists (select 1 from public.supervisor_site_assignments a where a.supervisor_id = requested.requested_id and a.site_id = saved_site_id and a.valid_to is null);
  if exists (select 1 from unnest(coalesce(p_supervisor_ids, array[]::bigint[])) as item(id) where not exists (select 1 from public.supervisors where supervisors.id = item.id)) then raise exception 'A selected supervisor was not found'; end if;
  insert into public.field_officer_site_assignments(field_officer_id, site_id, valid_from, created_by)
  select requested_id, saved_site_id, current_date, p_actor_id
  from (select distinct unnest(coalesce(p_field_officer_ids, array[]::bigint[])) as requested_id) requested
  where exists (select 1 from public.field_officers where id = requested.requested_id)
    and not exists (select 1 from public.field_officer_site_assignments a where a.field_officer_id = requested.requested_id and a.site_id = saved_site_id and a.valid_to is null);
  if exists (select 1 from unnest(coalesce(p_field_officer_ids, array[]::bigint[])) as item(id) where not exists (select 1 from public.field_officers where field_officers.id = item.id)) then raise exception 'A selected field officer was not found'; end if;

  return saved_site_id;
end;
$$;

