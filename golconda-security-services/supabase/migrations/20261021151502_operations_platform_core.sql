create or replace function operations_private.audit_operations_change()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog
as $$
declare
  old_value jsonb;
  new_value jsonb;
  row_data jsonb;
begin
  if tg_op = 'INSERT' then new_value := to_jsonb(new); row_data := new_value;
  elsif tg_op = 'UPDATE' then old_value := to_jsonb(old); new_value := to_jsonb(new); row_data := new_value;
  else old_value := to_jsonb(old); row_data := old_value;
  end if;
  insert into public.operations_audit_log(table_name, record_id, action, before_data, after_data, actor_id)
  values (tg_table_name, coalesce(row_data ->> 'id', ''), tg_op, old_value, new_value, auth.uid());
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

create or replace function public.validate_advance_adjustment()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
declare
  original_amount numeric(12,2);
  current_adjustment_total numeric(12,2);
  recovered_total numeric(12,2);
begin
  perform pg_advisory_xact_lock(new.advance_id);
  select amount into original_amount from public.advances where id = new.advance_id for update;
  if original_amount is null then raise exception 'Advance record was not found'; end if;
  select coalesce(sum(amount_delta), 0) into current_adjustment_total
  from public.advance_adjustments where advance_id = new.advance_id;
  select coalesce(sum(amount), 0) into recovered_total
  from public.advance_recoveries where advance_id = new.advance_id;
  if new.adjustment_type = 'reversal' and new.amount_delta <> -(original_amount + current_adjustment_total - recovered_total) then
    raise exception 'Reversal must cancel the exact remaining advance balance';
  end if;
  if original_amount + current_adjustment_total + new.amount_delta <= 0 and new.adjustment_type <> 'reversal' then
    raise exception 'Adjustment must leave a positive remaining advance balance';
  end if;
  if exists (select 1 from public.advance_recoveries where advance_id = new.advance_id)
    and original_amount + current_adjustment_total + new.amount_delta <
      (select coalesce(sum(amount), 0) from public.advance_recoveries where advance_id = new.advance_id) then
    raise exception 'Adjustment cannot reduce an advance below the amount already recovered';
  end if;
  return new;
end;
$$;

create or replace function public.validate_advance_recovery()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
declare
  original_amount numeric(12,2);
  adjustment_total numeric(12,2);
  recovered_total numeric(12,2);
begin
  perform pg_advisory_xact_lock(new.advance_id);
  select amount into original_amount from public.advances where id = new.advance_id for update;
  if original_amount is null then raise exception 'Advance record was not found'; end if;
  select coalesce(sum(amount_delta), 0) into adjustment_total from public.advance_adjustments where advance_id = new.advance_id;
  select coalesce(sum(amount), 0) into recovered_total from public.advance_recoveries where advance_id = new.advance_id;
  if new.amount + recovered_total > original_amount + adjustment_total then
    raise exception 'Recovery exceeds the remaining advance balance';
  end if;
  return new;
end;
$$;

