  p_site_id bigint,
  p_employee_type text,
  p_employee_id bigint,
  p_from timestamptz,
  p_to timestamptz,
  p_actor_id uuid
)
returns numeric
language plpgsql
security invoker
set search_path = pg_catalog
as $$
declare total_value numeric(14,2);
begin
  if p_actor_id is null or not exists (select 1 from public.admin_users where user_id = p_actor_id) then raise exception 'Administrator access is required'; end if;
  if p_employee_type is not null and p_employee_type not in ('guard', 'supervisor', 'field_officer') then raise exception 'Employee type is invalid'; end if;
  if p_employee_id is not null and p_employee_type is null then raise exception 'Employee type is required when filtering by employee'; end if;
  perform set_config('request.jwt.claim.sub', p_actor_id::text, true);
  select coalesce(sum(advance.amount), 0)::numeric(14,2) into total_value
  from public.advances advance
  where (p_site_id is null or advance.site_id = p_site_id)
    and (p_from is null or advance.occurred_at >= p_from)
    and (p_to is null or advance.occurred_at < p_to)
    and (p_employee_type is null or advance.employee_type = p_employee_type)
    and (p_employee_id is null
      or (advance.employee_type = 'guard' and advance.guard_id = p_employee_id)
      or (advance.employee_type = 'supervisor' and advance.supervisor_id = p_employee_id)
      or (advance.employee_type = 'field_officer' and advance.field_officer_id = p_employee_id));
  return total_value;
end;
