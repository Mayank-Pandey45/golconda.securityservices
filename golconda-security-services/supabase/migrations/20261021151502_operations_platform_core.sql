        where supervisor_id = person_id_value and valid_to is null;
        update public.supervisor_reporting set valid_to = current_date
        where supervisor_id = person_id_value and valid_to is null;
      else
        insert into public.supervisor_site_assignments(supervisor_id, site_id, valid_from, created_by)
        values (person_id_value, site_id_value, coalesce(joining_date_value, current_date), p_actor_id)
