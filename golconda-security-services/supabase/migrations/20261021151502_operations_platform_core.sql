      esi_contribution_rate = excluded.esi_contribution_rate,
      pf_applicable = excluded.pf_applicable,
      pf_contribution_rate = excluded.pf_contribution_rate,
      payroll_notes = excluded.payroll_notes,
      updated_at = now()
    returning id, (xmax = 0) into site_id_value, created_row;
    if created_row then created_sites := created_sites + 1; else updated_sites := updated_sites + 1; end if;

    for person_record in select value from jsonb_array_elements(coalesce(site_record -> 'guards', '[]'::jsonb)) loop
      joining_date_value := nullif(person_record ->> 'joining_date', '')::date;
      employee_status_value := lower(btrim(coalesce(nullif(person_record ->> 'status', ''), 'active')));
      email_value := nullif(lower(btrim(person_record ->> 'email')), '');
      insert into public.guards(employee_code, full_name, phone, email, designation, status, joining_date, site_id, updated_at)
      values (
        coalesce(nullif(upper(btrim(person_record ->> 'employee_code')), ''), 'GSS-GRD-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))), btrim(person_record ->> 'full_name'),
