      ) on conflict (phone_normalized) where phone_normalized <> ''
      do update set full_name = excluded.full_name, email = excluded.email, designation = excluded.designation,
        status = excluded.status, joining_date = coalesce(excluded.joining_date, guards.joining_date), updated_at = now()
      returning id, (xmax = 0) into person_id_value, created_row;
