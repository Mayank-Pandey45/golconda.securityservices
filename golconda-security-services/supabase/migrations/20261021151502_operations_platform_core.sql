        get diagnostics rows_added = row_count;
        added_relationships := added_relationships + rows_added;
      end if;
      salary_value := nullif(person_record ->> 'gross_monthly_salary', '')::numeric;
      if salary_value is not null then
        salary_date_value := coalesce(nullif(person_record ->> 'salary_effective_from', '')::date, joining_date_value, current_date);
        insert into public.employee_compensation(employee_type, supervisor_id, gross_monthly_salary, effective_from, notes, created_by)
        values ('supervisor', person_id_value, salary_value, salary_date_value, 'Imported through site spreadsheet', p_actor_id)
        on conflict (supervisor_id, effective_from) where supervisor_id is not null do update set
          gross_monthly_salary = excluded.gross_monthly_salary, notes = excluded.notes;
      end if;
    end loop;

    for person_record in select value from jsonb_array_elements(coalesce(site_record -> 'field_officers', '[]'::jsonb)) loop
      joining_date_value := nullif(person_record ->> 'joining_date', '')::date;
      employee_status_value := lower(btrim(coalesce(nullif(person_record ->> 'status', ''), 'active')));
