-- endpoint that has already verified an admin session. Stable matching is by
-- site_code and, for each employee type, normalized phone number. Names alone
-- are never used as identifiers. Existing unrelated rows are never deleted.
create or replace function public.import_operations_sites(p_sites jsonb, p_actor_id uuid)
returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog
as $$
declare
  site_record jsonb;
  person_record jsonb;
  site_id_value bigint;
  person_id_value bigint;
  created_row boolean;
  created_sites integer := 0;
  updated_sites integer := 0;
  created_guards integer := 0;
  updated_guards integer := 0;
  created_supervisors integer := 0;
  updated_supervisors integer := 0;
  created_field_officers integer := 0;
  updated_field_officers integer := 0;
  added_relationships integer := 0;
  rows_added integer := 0;
  joining_date_value date;
  employee_status_value text;
  salary_date_value date;
  salary_value numeric(12,2);
  email_value text;
begin
  if p_actor_id is null or not exists (select 1 from public.admin_users where user_id = p_actor_id) then
    raise exception 'Administrator access is required';
  end if;
  perform set_config('request.jwt.claim.sub', p_actor_id::text, true);
  if jsonb_typeof(p_sites) <> 'array' or jsonb_array_length(p_sites) = 0 or jsonb_array_length(p_sites) > 2000 then
    raise exception 'Import must contain between 1 and 2,000 validated sites';
  end if;

  for site_record in select value from jsonb_array_elements(p_sites) loop
    insert into public.sites (
      site_code, title, phone_numbers, total_salary, service_taken, given_emails, status,
      security_guard_monthly_billing, aso_monthly_billing, payroll_effective_date,
      esi_applicable, esi_contribution_rate, pf_applicable, pf_contribution_rate, payroll_notes
    ) values (
      upper(btrim(site_record ->> 'site_code')), btrim(site_record ->> 'title'),
      coalesce(site_record ->> 'phone_numbers', ''), coalesce(site_record ->> 'total_salary', ''),
      coalesce(site_record ->> 'service_taken', 'SECURITY GUARD'), coalesce(site_record ->> 'given_emails', ''),
      coalesce(site_record ->> 'status', 'active'),
      nullif(site_record ->> 'security_guard_monthly_billing', '')::numeric,
      nullif(site_record ->> 'aso_monthly_billing', '')::numeric,
      nullif(site_record ->> 'payroll_effective_date', '')::date,
      nullif(site_record ->> 'esi_applicable', '')::boolean,
      nullif(site_record ->> 'esi_contribution_rate', '')::numeric,
      nullif(site_record ->> 'pf_applicable', '')::boolean,
      nullif(site_record ->> 'pf_contribution_rate', '')::numeric,
      coalesce(site_record ->> 'payroll_notes', '')
    ) on conflict (lower(site_code)) where site_code is not null and btrim(site_code) <> ''
    do update set
      title = excluded.title,
      phone_numbers = excluded.phone_numbers,
      total_salary = excluded.total_salary,
      service_taken = excluded.service_taken,
      given_emails = excluded.given_emails,
      status = excluded.status,
      security_guard_monthly_billing = excluded.security_guard_monthly_billing,
      aso_monthly_billing = excluded.aso_monthly_billing,
      payroll_effective_date = excluded.payroll_effective_date,
