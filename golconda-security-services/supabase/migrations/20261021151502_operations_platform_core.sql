      values (
        coalesce(nullif(upper(btrim(person_record ->> 'employee_code')), ''), 'GSS-FO-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))),
        btrim(person_record ->> 'full_name'), btrim(person_record ->> 'phone'), email_value,
        coalesce(nullif(btrim(person_record ->> 'designation'), ''), 'Field Officer'),
        employee_status_value, joining_date_value, now()
      ) on conflict (phone_normalized) where phone_normalized <> ''
      do update set full_name = excluded.full_name, email = excluded.email, designation = excluded.designation,
        status = excluded.status, joining_date = coalesce(excluded.joining_date, field_officers.joining_date), updated_at = now()
      returning id, (xmax = 0) into person_id_value, created_row;
      if created_row then created_field_officers := created_field_officers + 1; else updated_field_officers := updated_field_officers + 1; end if;
