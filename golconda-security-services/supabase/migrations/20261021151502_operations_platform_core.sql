-- Guard profile editing uses the same historical multi-site assignment model
-- as supervisors and field officers. guards.site_id remains a compatibility
-- pointer maintained by the assignment trigger above.
create or replace function public.save_guard_profile(
  p_guard_id bigint,
  p_person jsonb,
  p_site_ids bigint[],
  p_actor_id uuid
)
returns bigint
language plpgsql
security invoker
set search_path = pg_catalog
as $$
declare
  guard_id_value bigint;
  site_ids_value bigint[] := coalesce(p_site_ids, array[]::bigint[]);
  salary_amount_value numeric(12,2) := nullif(p_person ->> 'salary_amount', '')::numeric;
  salary_frequency_value text := coalesce(nullif(p_person ->> 'salary_frequency', ''), 'monthly');
  salary_date_value date;
begin
  if p_actor_id is null or not exists (select 1 from public.admin_users where user_id = p_actor_id) then raise exception 'Administrator access is required'; end if;
  if length(btrim(coalesce(p_person ->> 'full_name', ''))) not between 1 and 160 then raise exception 'A guard name of 1 to 160 characters is required'; end if;
  if length(regexp_replace(coalesce(p_person ->> 'phone', ''), '\D', '', 'g')) not between 10 and 15 then raise exception 'A valid guard phone is required'; end if;
  if coalesce(p_person ->> 'status', 'active') not in ('active', 'inactive', 'on_leave', 'relieved') then raise exception 'Guard status is invalid'; end if;
  if salary_frequency_value not in ('monthly', 'daily') then raise exception 'Salary frequency is invalid'; end if;
  if cardinality(site_ids_value) <> (select count(distinct item.id) from unnest(site_ids_value) as item(id)) then raise exception 'Site assignments contain duplicates'; end if;
  if exists (select 1 from unnest(site_ids_value) as item(id) where not exists (select 1 from public.sites where id = item.id)) then raise exception 'A selected site was not found'; end if;
  if coalesce(p_person ->> 'status', 'active') in ('inactive', 'relieved') then site_ids_value := array[]::bigint[]; end if;
  perform set_config('request.jwt.claim.sub', p_actor_id::text, true);

  if p_guard_id is null then
    insert into public.guards(employee_code, full_name, phone, email, designation, status, joining_date,
      employment_end_date, date_of_birth, residential_address, photo_storage_path, salary_amount,
      salary_frequency, salary_effective_date, salary_notes, updated_at)
    values (coalesce(nullif(upper(btrim(p_person ->> 'employee_code')), ''), 'GSS-GRD-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12))),
      btrim(p_person ->> 'full_name'), btrim(p_person ->> 'phone'), nullif(lower(btrim(p_person ->> 'email')), ''),
      coalesce(nullif(btrim(p_person ->> 'designation'), ''), 'Security Guard'), coalesce(p_person ->> 'status', 'active'),
      nullif(p_person ->> 'joining_date', '')::date, nullif(p_person ->> 'employment_end_date', '')::date,
      nullif(p_person ->> 'date_of_birth', '')::date, nullif(p_person ->> 'residential_address', ''),
      nullif(p_person ->> 'photo_storage_path', ''), salary_amount_value, salary_frequency_value,
      nullif(p_person ->> 'salary_effective_date', '')::date, coalesce(p_person ->> 'salary_notes', ''), now())
    returning id into guard_id_value;
  else
    update public.guards set
      employee_code = coalesce(nullif(upper(btrim(p_person ->> 'employee_code')), ''), employee_code),
      full_name = btrim(p_person ->> 'full_name'), phone = btrim(p_person ->> 'phone'),
      email = nullif(lower(btrim(p_person ->> 'email')), ''),
      designation = coalesce(nullif(btrim(p_person ->> 'designation'), ''), 'Security Guard'),
      status = coalesce(p_person ->> 'status', 'active'), joining_date = nullif(p_person ->> 'joining_date', '')::date,
      employment_end_date = nullif(p_person ->> 'employment_end_date', '')::date,
      date_of_birth = nullif(p_person ->> 'date_of_birth', '')::date,
      residential_address = nullif(p_person ->> 'residential_address', ''),
      photo_storage_path = nullif(p_person ->> 'photo_storage_path', ''), salary_amount = salary_amount_value,
      salary_frequency = salary_frequency_value, salary_effective_date = nullif(p_person ->> 'salary_effective_date', '')::date,
      salary_notes = coalesce(p_person ->> 'salary_notes', ''), updated_at = now()
    where id = p_guard_id returning id into guard_id_value;
    if guard_id_value is null then raise exception 'Guard was not found'; end if;
  end if;

  update public.guard_site_assignments set valid_to = current_date
  where guard_id = guard_id_value and valid_to is null and not (site_id = any(site_ids_value));
  insert into public.guard_site_assignments(guard_id, site_id, valid_from, created_by)
  select guard_id_value, requested.id, current_date, p_actor_id from unnest(site_ids_value) as requested(id)
  where not exists (select 1 from public.guard_site_assignments a where a.guard_id = guard_id_value and a.site_id = requested.id and a.valid_to is null);

  salary_date_value := coalesce(nullif(p_person ->> 'salary_effective_date', '')::date, current_date);
  if exists (select 1 from public.employee_compensation c where c.guard_id = guard_id_value and c.effective_from > salary_date_value) then
    raise exception 'Use the latest compensation effective date or edit its existing record';
  end if;
  update public.employee_compensation set effective_to = salary_date_value - 1
    where guard_id = guard_id_value and effective_from < salary_date_value and effective_to is null;
  if salary_amount_value is not null and salary_frequency_value = 'monthly' then
    insert into public.employee_compensation(employee_type, guard_id, gross_monthly_salary, effective_from, notes, created_by)
      values ('guard', guard_id_value, salary_amount_value, salary_date_value, coalesce(p_person ->> 'salary_notes', ''), p_actor_id)
      on conflict (guard_id, effective_from) where guard_id is not null do update
        set gross_monthly_salary = excluded.gross_monthly_salary, notes = excluded.notes;
  else
    -- A daily rate is stored on the guard profile but the application does not
    -- track attendance, so it must not leave an earlier monthly salary active.
    -- The audit trigger retains the removed effective-date row for review.
    delete from public.employee_compensation
      where guard_id = guard_id_value and effective_from = salary_date_value;
  end if;
  return guard_id_value;
end;
$$;
revoke all on function public.save_guard_profile(bigint, jsonb, bigint[], uuid) from public, anon, authenticated;
grant execute on function public.save_guard_profile(bigint, jsonb, bigint[], uuid) to service_role;

create or replace function public.delete_guard_if_unreferenced(p_guard_id bigint, p_actor_id uuid)
returns boolean
language plpgsql
security invoker
set search_path = pg_catalog
as $$
begin
  if p_actor_id is null or not exists (select 1 from public.admin_users where user_id = p_actor_id) then raise exception 'Administrator access is required'; end if;
  perform set_config('request.jwt.claim.sub', p_actor_id::text, true);
  if exists (select 1 from public.guard_site_assignments where guard_id = p_guard_id)
    or exists (select 1 from public.employee_compensation where guard_id = p_guard_id)
