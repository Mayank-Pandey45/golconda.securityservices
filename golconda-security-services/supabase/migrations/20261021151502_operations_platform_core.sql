create or replace function public.sync_guard_legacy_site_pointer()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
declare
  affected_guard_id bigint;
  next_site_id bigint;
begin
  affected_guard_id := coalesce(new.guard_id, old.guard_id);
  select assignment.site_id into next_site_id
  from public.guard_site_assignments as assignment
  where assignment.guard_id = affected_guard_id and assignment.valid_to is null
  order by assignment.created_at, assignment.id
  limit 1;
  update public.guards as guard
  set site_id = next_site_id
  where guard.id = affected_guard_id and guard.site_id is distinct from next_site_id;
  return null;
end;
$$;

create or replace function public.sync_guard_legacy_assignment()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  if pg_trigger_depth() > 1 then return new; end if;
  if tg_op = 'INSERT' then
    if new.site_id is not null then
      insert into public.guard_site_assignments (guard_id, site_id, valid_from, assignment_notes)
      values (new.id, new.site_id, coalesce(new.joining_date, current_date), 'Migrated from legacy guards.site_id')
      on conflict (guard_id, site_id) where valid_to is null do nothing;
    end if;
  elsif new.site_id is distinct from old.site_id then
    if new.site_id is null then
      update public.guard_site_assignments set valid_to = current_date
      where guard_id = new.id and valid_to is null;
    else
      insert into public.guard_site_assignments (guard_id, site_id, valid_from, assignment_notes)
      values (new.id, new.site_id, coalesce(new.joining_date, current_date), 'Added through legacy guards.site_id compatibility')
      on conflict (guard_id, site_id) where valid_to is null do nothing;
    end if;
  end if;
  return new;
end;
$$;

