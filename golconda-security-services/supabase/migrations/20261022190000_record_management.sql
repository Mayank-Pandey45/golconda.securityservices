create or replace function public.manage_admin_record(
 p_table text,p_id bigint,p_action text,p_patch jsonb,p_confirmation text,p_actor_id uuid)
returns jsonb language plpgsql security invoker set search_path=pg_catalog as $$
declare current_record jsonb; result_record jsonb; allowed text[]; updates text; t text; fk record;
 linked boolean; today date := (now() at time zone 'Asia/Kolkata')::date; operational boolean;
begin
  if p_actor_id is null or not exists(select 1 from public.admin_users where user_id=p_actor_id) then raise exception using errcode='42501',message='Administrator access is required.'; end if;
  if p_table is null or p_table not in ('guards','supervisors','field_officers','sites','services','events','notifications','profile_docs','contact_submissions','job_applications','complaints') then raise exception using errcode='22023',message='Unsupported module.'; end if;
  perform set_config('request.jwt.claim.sub',p_actor_id::text,true);
  operational := p_table in ('guards','supervisors','field_officers','sites');
  if p_id is not null then
    execute format('select to_jsonb(r) from public.%I r where id=$1 for update',p_table) into current_record using p_id;
    if current_record is null then raise exception using errcode='P0002',message='Record not found.'; end if;
    perform set_config('app.lifecycle_write',p_table||':'||p_id::text,true);
  elsif p_action<>'save' then raise exception using errcode='22023',message='Record ID is required.'; end if;

  if p_action='restore' and current_record->>'archived_at' is null then raise exception using errcode='22023',message='This record is not archived.'; end if;
  if p_action='save' then
    allowed := case p_table
      when 'services' then array['title','description','image_url','tag','icon_key','sort_order']
      when 'events' then array['title','description','event_date','image_url','event_type','display_status','sort_order']
      when 'notifications' then array['title','message','notification_type','display_date','sort_order','notification_severity','starts_at','expires_at','is_active','is_published','dismissible','button_label','button_url']
      when 'profile_docs' then array['title','description','file_url','storage_path','category','mime_type','media_type','is_public','sort_order']
      when 'contact_submissions' then array['admin_notes','status']
      when 'job_applications' then array['admin_notes','status']
      when 'complaints' then array['admin_notes','status']
      else array[]::text[] end;
    if p_patch is null or jsonb_typeof(p_patch)<>'object' or p_patch='{}'::jsonb or exists(select 1 from jsonb_object_keys(p_patch) k where not(k=any(allowed))) then raise exception using errcode='22023',message='Unsupported record fields.'; end if;
    if current_record->>'archived_at' is not null then raise exception using errcode='55000',message='Restore before editing.'; end if;
    if p_id is null and p_table in ('contact_submissions','job_applications','complaints') then raise exception using errcode='22023',message='Use the public intake endpoint.'; end if;
    if p_id is null then
      select string_agg(format('%I',k),',' order by k) into updates from jsonb_object_keys(p_patch) k;
      execute format('insert into public.%I (%s) select %s from jsonb_populate_record(null::public.%I,$1) returning to_jsonb(%I.*)',p_table,updates,updates,p_table,p_table) into result_record using p_patch;
      p_id := (result_record->>'id')::bigint;
    else
      select string_agg(format('%I=v.%I',k,k),',' order by k) into updates from jsonb_object_keys(p_patch) k;
      execute format('update public.%I r set %s from jsonb_populate_record(null::public.%I,$1) v where r.id=$2 returning to_jsonb(r.*)',p_table,updates,p_table) into result_record using p_patch,p_id;
    end if;
    if p_table='complaints' and p_patch ? 'status' then
      update public.complaints set resolved_at=case when status='resolved' then coalesce(resolved_at,now()) else null end,updated_at=now() where id=p_id;
    end if;

  elsif p_action='delete' then
    if p_confirmation is distinct from 'DELETE '||p_id::text then raise exception using errcode='22023',message='Exact permanent-delete confirmation is required.'; end if;
    if current_record->>'archived_at' is null then raise exception using errcode='55000',message='Archive before permanent deletion.'; end if;
    if p_table in ('contact_submissions','job_applications','complaints') then raise exception using errcode='55000',message='Retention policy pending; archive only.'; end if;
    if p_table='profile_docs' and (current_record->>'category'='Registration & Compliance' or exists(select 1 from public.operations_audit_log where table_name='profile_docs' and record_id=p_id::text and (before_data->>'category'='Registration & Compliance' or after_data->>'category'='Registration & Compliance'))) then raise exception using errcode='55000',message='Compliance retention requires owner review; archive only.'; end if;
    if operational and exists(select 1 from public.operations_audit_log where table_name=p_table and record_id=p_id::text) then raise exception using errcode='55000',message='Operational audit history must be preserved.'; end if;
    -- Check ALL inbound FKs, including CASCADE and SET NULL, before DELETE.
    -- Parent FOR UPDATE and the FK locks serialize concurrent new references.
    for fk in select c.conrelid::regclass as child, a.attname as field, cardinality(c.conkey) as n, pa.attname as parent_field
      from pg_constraint c join pg_attribute a on a.attrelid=c.conrelid and a.attnum=c.conkey[1]
      join pg_attribute pa on pa.attrelid=c.confrelid and pa.attnum=c.confkey[1]
      where c.contype='f' and c.confrelid=to_regclass('public.'||p_table) loop
      if fk.n<>1 or fk.parent_field<>'id' then raise exception using errcode='55000',message='Composite dependency requires manual review.'; end if;
      execute format('select exists(select 1 from %s where %I=$1)',fk.child,fk.field) into linked using p_id;
      if linked then raise exception using errcode='55000',message='Related records must be retained.',hint='Linked assignments, compensation, advances or business records exist. Archive instead.'; end if;
    end loop;
    if p_table='services' and (exists(select 1 from public.contact_submissions where lower(service)=lower(current_record->>'title'))
      or exists(select 1 from public.job_applications where lower(role)=lower(current_record->>'title'))) then
      raise exception using errcode='55000',message='This service is referenced by retained intake records.';
    end if;
    perform set_config('app.lifecycle_delete',p_table||':'||p_id::text,true);
    execute format('delete from public.%I where id=$1',p_table) using p_id;
    return jsonb_build_object('id',p_id,'action','delete','message','Record removed. Any orphaned private file requires separately confirmed cleanup.');

  elsif p_action in ('archive','restore','activate','deactivate','hide','close','reopen') then
    if current_record->>'archived_at' is not null and p_action not in ('restore','archive') then raise exception using errcode='55000',message='Restore the archived record first.'; end if;
    if p_action='archive' then
      execute format('update public.%I set archived_at=coalesce(archived_at,now()),archived_by=$2 where id=$1',p_table) using p_id,p_actor_id;
    elsif p_action='restore' then
      execute format('update public.%I set archived_at=null,archived_by=null where id=$1',p_table) using p_id;
    end if;
    if operational then
      if p_action not in ('archive','restore','activate','deactivate') then raise exception using errcode='22023',message='Unsupported operational action.'; end if;
      if p_action='activate' and (current_record->>'employment_end_date')::date < today then raise exception using errcode='55000',message='Review the employment end date before activation.'; end if;
      execute format('update public.%I set status=$2 where id=$1',p_table) using p_id,case when p_action='activate' then 'active' else 'inactive' end;
      if p_action<>'activate' then
        if p_table='sites' then
          update public.guard_site_assignments set valid_to=greatest(valid_from,today) where site_id=p_id and valid_to is null;
          update public.supervisor_site_assignments set valid_to=greatest(valid_from,today) where site_id=p_id and valid_to is null;
          update public.field_officer_site_assignments set valid_to=greatest(valid_from,today) where site_id=p_id and valid_to is null;
          update public.guards g set site_id=(select min(a.site_id) from public.guard_site_assignments a join public.sites s on s.id=a.site_id where a.guard_id=g.id and a.valid_to is null and s.archived_at is null and s.status='active') where g.site_id=p_id;
        else
          t:=case p_table when 'guards' then 'guard' when 'supervisors' then 'supervisor' else 'field_officer' end;
          execute format('update public.%I set valid_to=greatest(valid_from,$2) where %I=$1 and valid_to is null',t||'_site_assignments',t||'_id') using p_id,today;
          if p_table='guards' then update public.guards set site_id=null where id=p_id;
          else execute format('update public.supervisor_reporting set valid_to=greatest(valid_from,$2) where %I=$1 and valid_to is null',t||'_id') using p_id,today; end if;
        end if;
      end if;
    elsif p_table in ('services','events','notifications') then
      if p_action not in ('archive','restore','activate','deactivate') then raise exception using errcode='22023',message='Unsupported content action.'; end if;
      execute format('update public.%I set is_active=$2 where id=$1',p_table) using p_id,p_action='activate';
      if p_table='notifications' and p_action<>'activate' then update public.notifications set is_published=false where id=p_id; end if;
    elsif p_table='profile_docs' then
      if p_action not in ('archive','restore','hide') then raise exception using errcode='22023',message='Use explicit public approval in the document editor.'; end if;
      update public.profile_docs set is_public=false where id=p_id;
    else
      if p_action not in ('archive','restore','close','reopen') then raise exception using errcode='22023',message='Unsupported intake action.'; end if;
      if p_action='close' then
        execute format('update public.%I set status=$2,updated_at=now() where id=$1',p_table) using p_id,case when p_table='complaints' then 'resolved' else 'closed' end;
      elsif p_action='reopen' then
        execute format('update public.%I set status=$2,updated_at=now() where id=$1',p_table) using p_id,case when p_table='complaints' then 'pending' else 'new' end;
      end if;
      if p_table='complaints' and p_action in ('close','reopen') then update public.complaints set resolved_at=case when p_action='close' then now() else null end where id=p_id; end if;
    end if;
  else raise exception using errcode='22023',message='Unsupported action.';
  end if;
  return jsonb_build_object('id',p_id,'action',p_action,'message',case when p_action='restore' then 'Record restored. Activation, publishing and assignments require separate review.' else 'Record action saved; history retained.' end);
end $$;
