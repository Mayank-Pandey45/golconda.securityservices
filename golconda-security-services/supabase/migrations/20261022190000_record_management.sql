      raise exception using errcode='55000', message='Unavailable sites cannot receive assignments.';
    end if;
    execute format('select id from public.%I where id=$1 and archived_at is null and status not in (%L,%L) for share',person_table,'inactive','relieved') into available_id using person_id;
    if available_id is null then raise exception using errcode='55000',message='Unavailable employees cannot receive assignments.'; end if;
  end if;
  return new;
end $$;

