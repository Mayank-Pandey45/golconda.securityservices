-- Prevent direct browser deletes, unsafe archived edits and accidental reactivation.
create or replace function operations_private.guard_record_lifecycle()
returns trigger language plpgsql security definer set search_path=pg_catalog as $$
declare data jsonb;
begin
  if tg_op='DELETE' then
    if current_setting('app.lifecycle_delete',true) is distinct from tg_table_name || ':' || old.id::text then
      raise exception using errcode='55000', message='Use the dependency-checked record-management API. Archive is available.';
    end if;
    return old;
  end if;
  data := to_jsonb(new);
  if tg_op='UPDATE' and tg_table_name in ('contact_submissions','job_applications','complaints')
    and (to_jsonb(new)-array['admin_notes','status','resolved_at','updated_at','archived_at','archived_by']) is distinct from (to_jsonb(old)-array['admin_notes','status','resolved_at','updated_at','archived_at','archived_by']) then
    raise exception using errcode='55000',message='Original submissions are immutable. Edit review notes and workflow status only.';
  end if;
  if tg_op='INSERT' and data->>'archived_at' is not null then
    raise exception using errcode='22023',message='New records cannot start archived.';
  elsif tg_op='UPDATE' then
    if (new.archived_at is distinct from old.archived_at or new.archived_by is distinct from old.archived_by)
       and current_setting('app.lifecycle_write',true) is distinct from tg_table_name || ':' || new.id::text then
      raise exception using errcode='42501',message='Use the lifecycle API to archive or restore.';
    end if;
    if old.archived_at is not null and current_setting('app.lifecycle_write',true) is distinct from tg_table_name || ':' || new.id::text then
      raise exception using errcode='55000',message='Restore the archived record before editing it.';
    end if;
  end if;
  return new;
end $$;

