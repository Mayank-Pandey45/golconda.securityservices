-- New advances cannot target an archived employee/site. Existing balances,
-- recoveries, corrections and payroll remain unchanged and accessible.
create or replace function operations_private.guard_archived_advance()
returns trigger language plpgsql security definer set search_path=pg_catalog as $$
declare t text; person_id bigint; available_id bigint;
begin
 t:=case new.employee_type when 'guard' then 'guards' when 'supervisor' then 'supervisors' when 'field_officer' then 'field_officers' else null end;
 if t is null then raise exception using errcode='22023',message='Invalid employee type.'; end if;
 person_id:=coalesce(new.guard_id,new.supervisor_id,new.field_officer_id);
 execute format('select id from public.%I where id=$1 and archived_at is null for share',t) into available_id using person_id;
 if available_id is null then raise exception using errcode='55000',message='Restore the archived employee before recording a new advance.'; end if;
 if new.site_id is not null then
   select id into available_id from public.sites where id=new.site_id and archived_at is null for share;
   if available_id is null then raise exception using errcode='55000',message='Restore the archived site before recording a new advance.'; end if;
 end if;
 return new;
end $$;
create trigger archived_advance_guard before insert on public.advances for each row execute function operations_private.guard_archived_advance();
revoke all on function operations_private.guard_archived_advance() from public,anon,authenticated;

