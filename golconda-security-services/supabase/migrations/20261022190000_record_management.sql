create or replace function public.queue_media_cleanup(p_bucket text,p_path text,p_actor_id uuid)
returns bigint language plpgsql security invoker set search_path=pg_catalog as $$
declare job_id bigint;
begin
  if not exists(select 1 from public.admin_users where user_id=p_actor_id) then raise exception using errcode='42501',message='Administrator access is required.'; end if;
  if p_bucket is null or p_bucket not in ('company-profile','employee-private') or p_path is null or length(p_path) not between 1 and 500 or p_path ~ '(^/|(^|/)\.\.?(/|$)|//)' then raise exception using errcode='22023',message='Invalid private object.'; end if;
  insert into public.media_cleanup_queue(bucket,path,requested_by) values(p_bucket,p_path,p_actor_id)
    on conflict(bucket,path) do update set status=case when media_cleanup_queue.status='processing' then 'processing' else 'pending' end,updated_at=now()
    returning id into job_id;
  return job_id;
end $$;
create or replace function public.claim_media_cleanup(p_id bigint,p_actor_id uuid)
returns jsonb language plpgsql security invoker set search_path=pg_catalog as $$
declare job public.media_cleanup_queue; claim_id uuid:=gen_random_uuid();
begin
  if not exists(select 1 from public.admin_users where user_id=p_actor_id) then raise exception using errcode='42501',message='Administrator access is required.'; end if;
  select * into job from public.media_cleanup_queue where id=p_id for update;
  if not found then raise exception using errcode='P0002',message='Cleanup job not found.'; end if;
  if job.status not in ('pending','retry','retained') then raise exception using errcode='55000',message='Cleanup already processed or reserved.'; end if;
  perform pg_advisory_xact_lock(hashtextextended(job.bucket||':'||job.path,0));
  if operations_private.media_is_referenced(job.bucket,job.path) then
    update public.media_cleanup_queue set status='retained',last_error='Referenced by a record or retained employee audit history.',updated_at=now() where id=p_id;
    return jsonb_build_object('blocked',true);
  end if;
  update public.media_cleanup_queue set status='processing',claim=claim_id,processed_by=p_actor_id,attempts=attempts+1,last_error=null,updated_at=now() where id=p_id;
  return jsonb_build_object('bucket',job.bucket,'path',job.path,'claim',claim_id);
end $$;
create or replace function public.complete_media_cleanup(p_id bigint,p_claim uuid,p_failed boolean,p_actor_id uuid)
returns void language plpgsql security invoker set search_path=pg_catalog as $$
begin
  if not exists(select 1 from public.admin_users where user_id=p_actor_id) then raise exception using errcode='42501',message='Administrator access is required.'; end if;
  update public.media_cleanup_queue set status=case when p_failed then 'retry' else 'deleted' end,claim=null,last_error=case when p_failed then 'Private Storage removal failed; retry explicitly.' else null end,updated_at=now() where id=p_id and claim=p_claim and status='processing';
  if not found then raise exception using errcode='55000',message='Cleanup claim changed; reconcile manually.'; end if;
end $$;
