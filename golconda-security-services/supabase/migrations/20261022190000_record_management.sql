-- Every attachment takes the same lock as the cleanup reservation. A file being
-- deleted cannot acquire new references; unknown or missing objects fail closed.
create or replace function operations_private.guard_media_reference()
returns trigger language plpgsql security definer set search_path=pg_catalog as $$
declare old_path text; new_path text; b text;
begin
  b := case when tg_table_name='profile_docs' then 'company-profile' else 'employee-private' end;
  new_path := case when tg_table_name='profile_docs' then to_jsonb(new)->>'storage_path' else to_jsonb(new)->>'photo_storage_path' end;
  if tg_op='UPDATE' then old_path := case when tg_table_name='profile_docs' then to_jsonb(old)->>'storage_path' else to_jsonb(old)->>'photo_storage_path' end; end if;
  if nullif(new_path,'') is not null and new_path is distinct from old_path then
    perform pg_advisory_xact_lock(hashtextextended(b || ':' || new_path, 0));
    if exists(select 1 from public.media_cleanup_queue where bucket=b and path=new_path and status='processing') then
      raise exception using errcode='55000', message='File cleanup is processing; upload a new file.';
    end if;
    if not exists(select 1 from storage.objects where bucket_id=b and name=new_path) then
      raise exception using errcode='22023', message='Private file was not found.';
    end if;
  end if;
  return new;
end $$;

