-- Private Telegram linking/confirmation state and encrypted employee identity metadata.
-- Full Aadhaar numbers are not collected or stored.
create table if not exists public.telegram_admin_links (
  admin_user_id uuid primary key references public.admin_users(user_id) on delete restrict,
  telegram_user_id text not null check (telegram_user_id ~ '^[0-9]{1,20}$'),
  linked_at timestamptz not null default now(), revoked_at timestamptz,
  revoked_by uuid references public.admin_users(user_id) on delete set null,
  created_at timestamptz not null default now()
);
create unique index if not exists telegram_admin_links_active_user_unique_idx on public.telegram_admin_links(telegram_user_id) where revoked_at is null;

create table if not exists public.telegram_link_codes (
  id uuid primary key default gen_random_uuid(),
  admin_user_id uuid not null references public.admin_users(user_id) on delete cascade,
  code_hash text not null unique check (code_hash ~ '^[0-9a-f]{64}$'),
  expires_at timestamptz not null, used_at timestamptz,
  created_at timestamptz not null default now(),
  created_by uuid not null references public.admin_users(user_id) on delete restrict
);
create index if not exists telegram_link_codes_admin_expiry_idx on public.telegram_link_codes(admin_user_id, expires_at desc) where used_at is null;

create table if not exists public.telegram_aliases (
  id bigint generated by default as identity primary key,
  alias text not null check (length(btrim(alias)) between 1 and 100),
  normalized_alias text not null check (length(btrim(normalized_alias)) between 1 and 100),
  entity_type text not null check (entity_type in ('guard','supervisor','field_officer','site','note')),
  guard_id bigint references public.guards(id) on delete cascade,
  supervisor_id bigint references public.supervisors(id) on delete cascade,
  field_officer_id bigint references public.field_officers(id) on delete cascade,
  site_id bigint references public.sites(id) on delete cascade,
  replacement text,
  created_by uuid not null references public.admin_users(user_id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint telegram_aliases_target_check check (
    (entity_type = 'guard' and guard_id is not null and supervisor_id is null and field_officer_id is null and site_id is null and replacement is null) or
    (entity_type = 'supervisor' and supervisor_id is not null and guard_id is null and field_officer_id is null and site_id is null and replacement is null) or
    (entity_type = 'field_officer' and field_officer_id is not null and guard_id is null and supervisor_id is null and site_id is null and replacement is null) or
    (entity_type = 'site' and site_id is not null and guard_id is null and supervisor_id is null and field_officer_id is null and replacement is null) or
    (entity_type = 'note' and replacement is not null and length(btrim(replacement)) between 1 and 100 and guard_id is null and supervisor_id is null and field_officer_id is null and site_id is null)
  )
);
create unique index if not exists telegram_aliases_normalized_unique_idx on public.telegram_aliases(normalized_alias);

create table if not exists public.telegram_pending_advances (
  id uuid primary key default gen_random_uuid(),
  telegram_user_id text not null check (telegram_user_id ~ '^[0-9]{1,20}$'),
  source_update_id bigint not null unique check (source_update_id >= 0),
  actor_id uuid not null references public.admin_users(user_id) on delete restrict,
  employee_type text not null check (employee_type in ('guard','supervisor','field_officer')),
  guard_id bigint references public.guards(id) on delete restrict,
  supervisor_id bigint references public.supervisors(id) on delete restrict,
  field_officer_id bigint references public.field_officers(id) on delete restrict,
  site_id bigint not null references public.sites(id) on delete restrict,
  amount numeric(12,2) not null check (amount > 0 and amount <= 10000000),
  occurred_at timestamptz not null, payment_mode text not null default '',
  description text not null default '', notes text not null default '',
  assignment_warning boolean not null default false,
  status text not null default 'awaiting_confirmation' check (status in ('awaiting_confirmation','saved','cancelled','expired')),
  expires_at timestamptz not null,
  saved_advance_id bigint references public.advances(id) on delete restrict,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  constraint telegram_pending_advance_employee_check check (
    (employee_type = 'guard' and guard_id is not null and supervisor_id is null and field_officer_id is null) or
    (employee_type = 'supervisor' and supervisor_id is not null and guard_id is null and field_officer_id is null) or
    (employee_type = 'field_officer' and field_officer_id is not null and guard_id is null and supervisor_id is null)
  )
);
create index if not exists telegram_pending_advances_sender_expiry_idx on public.telegram_pending_advances(telegram_user_id, expires_at desc) where status = 'awaiting_confirmation';

create table if not exists public.telegram_update_receipts (
  update_id bigint primary key check (update_id >= 0),
  received_at timestamptz not null default now(), expires_at timestamptz not null default (now() + interval '30 days')
);
create index if not exists telegram_update_receipts_expiry_idx on public.telegram_update_receipts(expires_at);

create table if not exists public.telegram_wizard_sessions (
  telegram_user_id text primary key check (telegram_user_id ~ '^[0-9]{1,20}$'),
  actor_id uuid not null references public.admin_users(user_id) on delete cascade,
  step text not null check (step in ('amount','details','edit_employee','edit_site','edit_amount','edit_date','edit_payment_mode','edit_notes')),
  draft jsonb not null default '{}'::jsonb check (jsonb_typeof(draft) = 'object'),
  expires_at timestamptz not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.telegram_bot_events (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.admin_users(user_id) on delete set null,
  telegram_user_id text check (telegram_user_id is null or telegram_user_id ~ '^[0-9]{1,20}$'),
  event_type text not null check (length(event_type) between 1 and 80),
  pending_id uuid references public.telegram_pending_advances(id) on delete set null,
  advance_id bigint references public.advances(id) on delete set null,
  details jsonb not null default '{}'::jsonb check (jsonb_typeof(details) = 'object'),
  created_at timestamptz not null default now()
);
create index if not exists telegram_bot_events_created_idx on public.telegram_bot_events(created_at desc);

create table if not exists public.employee_identity_documents (
  employee_type text not null check (employee_type in ('guard','supervisor','field_officer')),
  employee_id bigint not null check (employee_id > 0),
  guard_id bigint references public.guards(id) on delete restrict,
  supervisor_id bigint references public.supervisors(id) on delete restrict,
  field_officer_id bigint references public.field_officers(id) on delete restrict,
  aadhaar_reference_ciphertext text, aadhaar_last4 text check (aadhaar_last4 is null or aadhaar_last4 ~ '^[0-9]{4}$'),
  pan_ciphertext text, pan_last4 text check (pan_last4 is null or pan_last4 ~ '^[A-Z0-9]{4}$'),
  other_id_type text check (other_id_type is null or length(other_id_type) between 1 and 80),
  other_id_ciphertext text, other_id_last4 text check (other_id_last4 is null or length(other_id_last4) between 1 and 4),
  updated_at timestamptz not null default now(), updated_by uuid not null references public.admin_users(user_id) on delete restrict,
  primary key (employee_type, employee_id),
  constraint employee_identity_employee_check check (
    (employee_type = 'guard' and guard_id = employee_id and supervisor_id is null and field_officer_id is null) or
    (employee_type = 'supervisor' and supervisor_id = employee_id and guard_id is null and field_officer_id is null) or
    (employee_type = 'field_officer' and field_officer_id = employee_id and guard_id is null and supervisor_id is null)
  ),
  constraint employee_identity_aadhaar_reference_only check (aadhaar_reference_ciphertext is null or aadhaar_last4 is not null)
);
create table if not exists public.employee_identity_audit (
  id bigint generated by default as identity primary key,
  employee_type text not null check (employee_type in ('guard','supervisor','field_officer')),
  employee_id bigint not null check (employee_id > 0),
  action text not null check (action in ('created','updated','cleared')),
  changed_fields text[] not null default '{}',
  changed_by uuid not null references public.admin_users(user_id) on delete restrict,
  changed_at timestamptz not null default now()
);
create index if not exists employee_identity_audit_employee_idx on public.employee_identity_audit(employee_type, employee_id, changed_at desc);

-- Keep sensitive-value writes and their audit event in one transaction.
create or replace function public.save_employee_identity(p_identity jsonb, p_changed_fields text[], p_actor_id uuid)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  identity_row public.employee_identity_documents%rowtype;
  existed boolean;
  action_value text;
begin
  if p_actor_id is null or not exists (select 1 from public.admin_users where user_id = p_actor_id) then
    raise exception 'Administrator authorization required' using errcode = '42501';
  end if;
  if p_identity is null or jsonb_typeof(p_identity) <> 'object' or p_changed_fields is null or cardinality(p_changed_fields) = 0
    or exists (select 1 from unnest(p_changed_fields) as field where field not in ('aadhaar_reference','pan_number','other_id_proof','other_id_type')) then
    raise exception 'Identity update is invalid' using errcode = '22023';
  end if;

  select exists (
    select 1 from public.employee_identity_documents
    where employee_type = p_identity ->> 'employee_type'
      and employee_id = (p_identity ->> 'employee_id')::bigint
  ) into existed;

  insert into public.employee_identity_documents (
    employee_type, employee_id, guard_id, supervisor_id, field_officer_id,
    aadhaar_reference_ciphertext, aadhaar_last4, pan_ciphertext, pan_last4,
    other_id_type, other_id_ciphertext, other_id_last4, updated_at, updated_by
  ) values (
    p_identity ->> 'employee_type', (p_identity ->> 'employee_id')::bigint,
    nullif(p_identity ->> 'guard_id','')::bigint, nullif(p_identity ->> 'supervisor_id','')::bigint, nullif(p_identity ->> 'field_officer_id','')::bigint,
    p_identity ->> 'aadhaar_reference_ciphertext', p_identity ->> 'aadhaar_last4',
    p_identity ->> 'pan_ciphertext', p_identity ->> 'pan_last4',
    p_identity ->> 'other_id_type', p_identity ->> 'other_id_ciphertext', p_identity ->> 'other_id_last4', now(), p_actor_id
  ) on conflict (employee_type, employee_id) do update set
    guard_id = excluded.guard_id, supervisor_id = excluded.supervisor_id, field_officer_id = excluded.field_officer_id,
    aadhaar_reference_ciphertext = excluded.aadhaar_reference_ciphertext, aadhaar_last4 = excluded.aadhaar_last4,
    pan_ciphertext = excluded.pan_ciphertext, pan_last4 = excluded.pan_last4,
    other_id_type = excluded.other_id_type, other_id_ciphertext = excluded.other_id_ciphertext,
    other_id_last4 = excluded.other_id_last4, updated_at = now(), updated_by = p_actor_id
  returning * into identity_row;

  action_value := case
    when identity_row.aadhaar_reference_ciphertext is null and identity_row.pan_ciphertext is null and identity_row.other_id_ciphertext is null then 'cleared'
    when existed then 'updated'
    else 'created'
  end;
  insert into public.employee_identity_audit(employee_type, employee_id, action, changed_fields, changed_by)
  values (identity_row.employee_type, identity_row.employee_id, action_value, p_changed_fields, p_actor_id);
  return to_jsonb(identity_row);
end;
$$;

-- The service API is the only access path; browser JWT roles receive no privileges or policies.
do $$
declare table_name text;
begin
  foreach table_name in array array[
    'telegram_admin_links','telegram_link_codes','telegram_aliases','telegram_pending_advances',
    'telegram_update_receipts','telegram_wizard_sessions','telegram_bot_events','employee_identity_documents','employee_identity_audit'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from public, anon, authenticated', table_name);
    execute format('grant all on table public.%I to service_role', table_name);
  end loop;
end;
$$;
revoke all on function public.save_employee_identity(jsonb, text[], uuid) from public, anon, authenticated;
grant execute on function public.save_employee_identity(jsonb, text[], uuid) to service_role;
revoke all on sequence public.telegram_aliases_id_seq, public.telegram_bot_events_id_seq, public.employee_identity_audit_id_seq from public, anon, authenticated;
grant usage, select on sequence public.telegram_aliases_id_seq, public.telegram_bot_events_id_seq, public.employee_identity_audit_id_seq to service_role;
