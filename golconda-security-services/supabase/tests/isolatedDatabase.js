// In-memory only: deliberately accepts no database URL, environment or credentials.
import { PGlite } from "@electric-sql/pglite";
import { readFile } from "node:fs/promises";
export const metadata = JSON.parse(await readFile(new URL("./production-schema-metadata.json", import.meta.url), "utf8"));
export const migration = await readFile(new URL("../migrations/20261022190000_record_management.sql", import.meta.url), "utf8");
export const lifecycleMigration = await readFile(new URL("../migrations/20261023153124_employee_exit_and_site_closure.sql", import.meta.url), "utf8");
const ident = value => '"' + value.replaceAll('"', '""') + '"';
export async function isolatedDatabase() {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon nologin; create role authenticated nologin;
      create role service_role nologin bypassrls;
      create schema auth; create schema storage; create schema operations_private;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$
        select coalesce(nullif(current_setting('request.jwt.claim.sub',true),''),
          nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub')::uuid
      $$;
      grant usage on schema public,auth,storage to anon,authenticated,service_role;
      grant execute on function auth.uid() to anon,authenticated,service_role;
      create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text not null,name text not null,unique(bucket_id,name));
      alter table storage.objects enable row level security;
      grant select,insert,update,delete on storage.objects to authenticated,service_role;
      set check_function_bodies=off;
    `);
    for (const table of new Set(metadata.columns.map(c=>c.tbl))) {
      const columns=metadata.columns.filter(c=>c.tbl===table).map(c=>`${ident(c.col)} ${c.typ}${c.generated ? ' generated always as ('+c.def+') stored' : c.identity ? ' generated by default as identity' : c.def ? ' default '+c.def : ''}${c.required ? ' not null' : ''}`);
      await db.exec(`create table public.${ident(table)} (${columns.join(',')});`);
    }
    for (const c of metadata.constraints) await db.exec(`alter table public.${ident(c.tbl)} add constraint ${ident(c.conname)} ${c.def};`);
    for (const sql of metadata.indexes) await db.exec(sql);
    for (const sql of metadata.functions) await db.exec(sql);
    for (const sql of metadata.triggers) await db.exec(sql);
    for (const table of metadata.rls) await db.exec(`alter table public.${ident(table)} enable row level security;`);
    for (const p of metadata.policies) {
      const roles=p.roles.map(r=>r==='public'?'public':ident(r)).join(',');
      await db.exec(`create policy ${ident(p.policyname)} on ${ident(p.schemaname)}.${ident(p.tablename)} as ${p.permissive} for ${p.cmd} to ${roles}${p.qual?' using ('+p.qual+')':''}${p.with_check?' with check ('+p.with_check+')':''};`);
    }
    for (const g of metadata.grants) await db.exec(`grant ${g.privilege_type} on public.${ident(g.table_name)} to ${g.grantee==='PUBLIC'?'public':ident(g.grantee)};`);
    await db.exec(`
      grant usage,select on all sequences in schema public to service_role;
      revoke all on all functions in schema public,operations_private from public,anon,authenticated;
      grant execute on all functions in schema public to service_role;
      -- Production postgres defaults auto-grant new public tables/functions/sequences.
      -- Reproduce them so migration tests catch missing explicit revocations.
      alter default privileges in schema public grant all on tables to anon,authenticated,service_role;
      alter default privileges in schema public grant execute on functions to anon,authenticated,service_role;
      alter default privileges in schema public grant all on sequences to anon,authenticated,service_role;
      set check_function_bodies=on;
    `);
    return db;
  } catch(error) { await db.close(); throw error; }
}
